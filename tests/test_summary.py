def wait_for(cond, seconds=5):
    t = time.time()
    while not cond() and time.time() - t < seconds:
        time.sleep(0.02)
    return cond()


def test_pages_get_summaries_from_the_abstract_in_the_background(client, corpus, monkeypatch, summaries_on):
    import serve

    pids = sorted(corpus)[:3]
    # visitors who aren't logged in never start a model call
    assert client.post('/summaries', data={'pids': ','.join(pids)}).get_json() == {'summaries': {}, 'pending': []}
    assert b'var summariesAsk = false' in client.get('/').data
    login(client)
    assert b'var summariesAsk = true' in client.get('/').data
    r = client.post('/summaries', data={'pids': ','.join(pids + ['nope'])}).get_json()
    assert r['summaries'] == {} and sorted(r['pending']) == pids  # being made
    assert wait_for(lambda: len(summaries_on) == 3)
    assert all(text == '' for _, text in summaries_on)  # from the abstract
    assert wait_for(lambda: len(client.post('/summaries', data={'pids': ','.join(pids)}).get_json()['summaries']) == 3)
    r = client.post('/summaries', data={'pids': ','.join(pids)}).get_json()
    assert r['pending'] == [] and r['summaries'][pids[0]]['source'] == 'abstract'
    assert len(summaries_on) == 3  # made once
    papers = client.get('/?rank=time&format=json').get_json()['papers']
    assert {p['id']: p['ai'] for p in papers if p['ai']}.keys() == set(pids)

    # a failure is tried again a day later, at most three times
    monkeypatch.setattr(summary, 'ask', lambda *a, **k: 'not json')
    other = sorted(corpus)[5]
    client.post('/summaries', data={'pids': other})
    with db.get_refs_db() as rdb:
        assert wait_for(lambda: (rdb.summaries_of([other]).get(other) or {}).get('status') == 'error')
    assert client.post('/summaries', data={'pids': other}).get_json()['pending'] == []

    # the daily cap
    monkeypatch.setattr(serve, 'SUMMARY_MAX_DAY', 4)
    rest = sorted(corpus)[10:14]
    r = client.post('/summaries', data={'pids': ','.join(rest)}).get_json()
    assert r['pending'] == []
    # off: nothing at all
    monkeypatch.setenv('SUMMARIES_ENABLED', '0')
    assert client.post('/summaries', data={'pids': ','.join(pids)}).get_json() == {'summaries': {}, 'pending': []}
    assert all(p['ai'] is None for p in client.get('/?rank=time&format=json').get_json()['papers'])


def test_every_paper_in_the_digest_mail_has_a_summary(features, corpus, monkeypatch, tmp_path, summaries_on):
    import send_emails

    v = sorted(corpus)
    for p in v[:4]:
        db.tag_paper('alice', p, 'cv')
    db.request_email('alice', 'alice@example.org')
    db.confirm_email('alice', 'alice@example.org')
    db.set_digest_days('alice', 30)
    now = time.time()
    db.set_last_digest(now - 8 * 86400)
    slot = send_emails.next_slot(now)
    clock = [slot - send_emails.PREPARE - 60]
    monkeypatch.setattr(time, 'time', lambda: clock[0])

    # hours before the slot, the digests are made, so enrich_daemon.py summarizes their papers first
    times, emails = db.get_papers_db().times(), db.get_emails()
    assert send_emails.prepare(features, times, emails, clock[0]) == 0  # too early
    clock[0] = slot - 3600
    assert send_emails.prepare(features, times, emails, clock[0]) == 1
    clock[0] = slot - 1800
    assert send_emails.prepare(features, times, emails, clock[0]) == 0  # once
    d = db.get_digest('alice')
    in_mail = [p for s in d['sections'] for p, _ in s['papers']]
    assert in_mail and set(in_mail) <= db.pending_digest_pids()
    with db.get_refs_db() as rdb:  # enrich_daemon.py got to one of them from the full text
        rdb.put_summary(in_mail[0], 'ok', 'm', 'html', json.loads(answer(problem='From the text.')))

    # at the slot those digests go out, and any paper still without a summary gets one from its abstract
    clock[0] = slot + 60
    assert send_emails.prepared(d, clock[0])
    out = tmp_path / 'digest.html'
    monkeypatch.setenv('PUBLIC_URL', 'https://sanity.example.org')
    monkeypatch.setattr(sys, 'argv', ['send_emails.py', '--if-due', '--dry-run', '1', '--save', str(out)])
    runpy.run_path(os.path.join(REPO, 'send_emails.py'), run_name='__main__')
    body = out.read_text()
    assert db.get_digest('alice')['sections'] == d['sections']  # the prepared one, not made again
    assert body.count('<b>Problem:</b>') == len(in_mail)
    assert (
        'From the text.' in body and 'full text, may contain errors' in body and 'abstract, may contain errors' in body
    )
    assert len(summaries_on) == len(in_mail) - 1 and all(text == '' for _, text in summaries_on)
    assert not send_emails.prepared(d, slot + 8 * 86400)


def test_a_refs_db_without_the_summaries_table_opens(tmp_path):
    import sqlite3

    path = str(tmp_path / 'refs.sqlite')
    con = sqlite3.connect(path)
    con.executescript(db.REFS_SCHEMA.split('CREATE TABLE IF NOT EXISTS summaries')[0])
    con.execute("INSERT INTO fetched (pid, status, t, tries, n, license) VALUES ('2601.00001', 'ok', 1, 1, 0, '')")
    con.commit()
    con.close()
    with db.get_refs_db(path) as rdb:
        assert rdb.fetched()['2601.00001'][0] == 'ok' and rdb.summaries_of(['2601.00001']) == {}
        rdb.put_summary('2601.00001', 'ok', 'm', 'html', json.loads(answer()))
        assert rdb.summary_of('2601.00001')['problem'] == 'Models forget things.'
