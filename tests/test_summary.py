LATEXML = (
    '<html><head><title>t</title><style>.x{}</style></head><body><nav>menu</nav>'
    '<article class="ltx_document"><h1 class="ltx_title">A Paper</h1>'
    '<div class="ltx_authors"><span class="ltx_role_author">Some One</span></div>'
    '<section class="ltx_section"><h2>1 Introduction</h2><p class="ltx_p">We study '
    '<math alttext="x^{2}" class="ltx_Math"><semantics><mi>x</mi></semantics></math> carefully.</p>'
    '<figure><figcaption>Figure 1: the setup.</figcaption></figure></section>'
    '<section class="ltx_bibliography"><ul class="ltx_biblist">' + bibitem(1, 'A cited paper') + '</ul></section>'
    '<section class="ltx_appendix"><h2>A Proofs</h2><p>Long proofs.</p></section>'
    '</article><footer class="ltx_page_footer">Generated by LaTeXML</footer></body></html>'
)


def answer(**over):
    f = {'problem': 'Models forget things.', 'approach': 'They add memory.', 'result': 'It helps a lot.', 'caveat': ''}
    f.update(over)
    return json.dumps(f)


@pytest.fixture
def summaries_on(monkeypatch):
    """summaries on, with the model replaced: returns the list of (title, text) it was asked about"""
    monkeypatch.setenv('SUMMARIES_ENABLED', '1')
    monkeypatch.setenv('OPENROUTER_API_KEY', 'sk-test')
    asked = []

    def ask(title, abstract, text, model=summary.MODEL, key=None, timeout=180):
        asked.append((title, text))
        return answer(problem=f'About {title[:20]}.')

    monkeypatch.setattr(summary, 'ask', ask)
    return asked


def test_the_main_text_leaves_out_references_appendix_and_authors():
    text = summary.html_text(LATEXML)
    assert 'We study $x^{2}$ carefully.' in text and 'Figure 1: the setup.' in text and 'A Paper' in text
    for gone in ('A cited paper', 'Long proofs', 'Some One', 'LaTeXML', 'menu', '.x{}'):
        assert gone not in text
    assert summary.html_text('<html>no LaTeXML here</html>') == 'no LaTeXML here'
    assert len(summary.html_text('<div class="ltx_document">' + 'word ' * 100_000 + '</div>')) == summary.MAX_TEXT
    pdf = 'Intro text.\n' * 50 + '\nReferences\n[1] A. Author. A paper.'
    assert summary.pdf_text(pdf).endswith('Intro text.')


def test_answers_are_checked_and_asked_again_once(monkeypatch):
    assert summary.check(answer(caveat=' Only  synthetic data. ')) == {
        'problem': 'Models forget things.',
        'approach': 'They add memory.',
        'result': 'It helps a lot.',
        'caveat': 'Only synthetic data.',
    }
    assert summary.check(answer(caveat='Empty string'))['caveat'] == ''
    for bad in ('not json', '[]', json.dumps({'problem': 'x'}), answer(approach=''), answer(result='word ' * 60)):
        with pytest.raises(summary.SummaryError):
            summary.check(bad)
    answers = iter([answer(problem=''), answer()])
    monkeypatch.setattr(summary, 'ask', lambda *a, **k: next(answers))
    assert summary.summarize('t', 'a', 'x')['problem'] == 'Models forget things.'
    answers = iter([answer(problem=''), answer(problem='')])
    with pytest.raises(summary.SummaryError):
        summary.summarize('t', 'a', 'x')


def test_saved_papers_are_summarized_from_their_text(client, corpus, monkeypatch, summaries_on):
    pids = sorted(corpus)
    with_html, without_html = pids[:2]
    login(client)
    for p in (with_html, without_html):
        client.post(f'/add/{p}/cv')
    asked = fake_arxiv(
        monkeypatch,
        {
            f'https://arxiv.org/html/{with_html}': LATEXML,
            f'https://arxiv.org/abs/{with_html}': '<html></html>',
            f'https://arxiv.org/abs/{without_html}': '<html></html>',
            f'https://arxiv.org/html/{without_html}': None,
            f'https://arxiv.org/pdf/{without_html}': None,
        },
    )
    run_daemon(monkeypatch)
    texts = {t[:20]: text for t, text in summaries_on}
    assert 'We study $x^{2}$' in texts[corpus[with_html]['title'][:20]]
    assert texts[corpus[without_html]['title'][:20]] == ''  # neither HTML nor PDF: the abstract
    with db.get_refs_db() as rdb:
        s = rdb.summaries_of([with_html, without_html])
    assert s[with_html]['status'] == 'ok' and s[with_html]['source'] == 'html'
    assert s[with_html]['problem'].startswith('About') and s[with_html]['model'] == summary.MODEL
    assert s[without_html]['source'] == 'notext'
    n = len(asked)
    run_daemon(monkeypatch)
    assert len(asked) == n and len(summaries_on) == 2  # done is done

    # cards carry it
    saved = {p['id']: p for p in client.get('/?rank=saved&tags=cv&format=json').get_json()['papers']}
    assert saved[with_html]['ai']['problem'].startswith('About')
    # and agents get it
    r = client.get(f'/api/get_papers?ids={with_html}').get_json()
    assert r['papers'][0]['ai_summary']['from'] == 'html'


